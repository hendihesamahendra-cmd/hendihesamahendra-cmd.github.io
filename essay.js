const params = new URLSearchParams(window.location.search);
const work = params.get("work");

const essay = essays[work];

const titleElement = document.getElementById("essay-title");
const metaElement = document.getElementById("essay-meta");
const subtitleElement = document.getElementById("essay-subtitle");
const contentElement = document.getElementById("essay-content");


if (!essay) {

  titleElement.textContent = "Essay not found";

  metaElement.textContent = "Archive";

  subtitleElement.textContent =
    "Tulisan yang kamu cari tidak ditemukan.";

  contentElement.innerHTML = `
    <div class="essay-error">
      The requested essay does not exist.
    </div>
  `;

} else {

  document.title = `${essay.title} — A Small Archive of Being.`;

  titleElement.textContent = essay.title;

  metaElement.textContent =
    `${essay.meta} · ${essay.year}`;

  subtitleElement.textContent = essay.subtitle;

  contentElement.innerHTML = essay.content;

}
